export function hill(c, [ec50, n, emax = 1]) {
  if (c <= 0) return 0;
  const x = Math.pow(c, n);
  return (emax * x) / (x + Math.pow(ec50, n));
}

const suave = (a, b, x) => {
  const t = Math.max(0, Math.min(1, (x - a) / (b - a)));
  return t * t * (3 - 2 * t);
};

// Ocupación D2 por PET (modelo hiperbólico, Kapur et al. 2000; Seeman 2002):
// ocupación = D / (D + DE50), con D en mg/día
export function ocupacionD2(dosis, ed50) {
  return dosis > 0 ? dosis / (dosis + ed50) : 0;
}

// Estado clínico (efectos 0..1) para un fármaco a una dosis relativa c
export function estadoClinico(farmaco, clase, c) {
  const e = {};
  const pd = { ...(clase.pd || {}), ...(farmaco.pd || {}) };
  for (const [k, p] of Object.entries(pd)) e[k] = hill(c, p);
  if (clase.d2 && farmaco.d2) {
    const dosis = c * farmaco.d2.dosisRef;
    const occ = ocupacionD2(dosis, farmaco.d2.ed50);
    e.ocupacionD2 = occ;
    const protec = farmaco.d2.proteccionSEP ?? 0;
    const intr = clase.intrinseca ?? 0;
    e.antipsicotico = suave(0.5, 0.68, occ);
    e.prolactina = suave(0.66, 0.82, occ) * (1 - (farmaco.d2.protegeProlactina ?? 0)) * (intr ? 0.1 : 1);
    e.sep = suave(0.76, 0.9, occ) * (1 - protec) * (intr ? 0.25 : 1);
    if (farmaco.d2.sedacionH1) e.sedacion = hill(c, [1 / farmaco.d2.sedacionH1, 1.4]);
  }
  e.ocupacion = clase.ocupacion ? hill(c, clase.ocupacion) : Math.min(1, c * 0.6);
  return e;
}

